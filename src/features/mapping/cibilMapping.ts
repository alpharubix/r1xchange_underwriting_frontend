/** Flatten nested CIBIL mappings for searching and drag-and-drop builders. */
function flattenCibilMapping(
  value: Record<string, unknown>,
  parentGroup = "",
): CibilParameterEntry[] {
  return Object.entries(value).flatMap(([key, child]) => {
    const group = parentGroup ? `${parentGroup}.${key}` : key;

    if (typeof child === "string") {
      return [{
        id: group,
        group: parentGroup || key,
        key,
        label: key.replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/^./, (c) => c.toUpperCase()),
        path: child,
      }];
    }

    if (child && typeof child === "object" && !Array.isArray(child)) {
      return flattenCibilMapping(child as Record<string, unknown>, group);
    }

    return [];
  });
}

export const ALL_CIBIL_PARAMETERS: CibilParameterEntry[] =
  flattenCibilMapping(CIBIL_PARAMETER_MAPPING as Record<string, unknown>);

/** Resolve a nested CIBIL path using a dot-separated mapping key. */
export function getCibilParameterPath(mappingKey: string): string | undefined {
  const value = mappingKey.split(".").reduce<unknown>((current, key) => {
    if (current && typeof current === "object") {
      return (current as Record<string, unknown>)[key];
    }
    return undefined;
  }, CIBIL_PARAMETER_MAPPING);

  return typeof value === "string" ? value : undefined;
}
