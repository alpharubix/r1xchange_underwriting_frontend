export type ItrParameterGroup = keyof typeof ITR_PARAMETER_MAPPING;

/** All available ITR parameter groups. */
export const ITR_PARAMETER_GROUPS = Object.keys(
  ITR_PARAMETER_MAPPING,
) as ItrParameterGroup[];

/** Resolve a mapped path from its group and parameter key. */
export function getItrParameterPath(
  group: ItrParameterGroup,
  parameter: string,
): string | undefined {
  const mapping: Record<string, string> = ITR_PARAMETER_MAPPING[group] as Record<
    string,
    string
  >;
  return mapping[parameter];
}

/** Flatten the mapping for searchable/draggable parameter lists. */
export const ALL_ITR_PARAMETERS = Object.entries(ITR_PARAMETER_MAPPING).flatMap(
  ([group, parameters]) =>
    Object.entries(parameters).map(([key, path]) => ({
      id: `${group}.${key}`,
      group: group as ItrParameterGroup,
      key,
      label: key.replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/^./, (c) => c.toUpperCase()),
      path,
    })),
);
